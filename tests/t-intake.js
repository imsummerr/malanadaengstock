process.env.TZ = 'Asia/Bangkok';
const { makeCheck } = require('./harness');
const { fresh } = require('./fixture');
const { eq, section, done } = makeCheck('รับของทางไลน์');

const ctx = { location: 'ครัวกลาง', who: 'เจ้าของ', msgId: 'm', isGroup: true };
function send(g, text, id) {
  return g.intakeSaveAndSummarize_(g.intakeParseText_(text), Object.assign({}, ctx, { msgId: id }),
                                   'ข้อความ', id, []);
}
const bal = g => g.stockBalances_()[g.CENTRAL] || {};

section('ข้อความจริง 25/9 — ไม่พัง ลงครบ');
let g = fresh();
let out = send(g, [
  'น้ำจิ้มงา 7 ถุง 627.2 บาท', 'น้ำดำ 9 ถุง 677.7 บาท', 'สาหร่าย 100 กรัม 86 บาท',
  'แมงกะพรุน 1 กก 85 บาท', 'วุ้นเส้นเกาหลี 0.5 โล 31 บาท', 'ถุงช้อปปิ้ง 9 บาท'
].join('\n'), 'r1');
eq('ตอบกลับได้', /บันทึกแล้ว/.test(out), true);
eq('ถุงช้อปปิ้งเป็นค่าใช้จ่าย', /🧾 ค่าใช้จ่าย\n• ถุงช้อปปิ้ง/.test(out), true);
eq('น้ำจิ้มงา 7 ถุง', bal(g)['น้ำจิ้มงา (ดิบ)'], 7);
eq('สาหร่าย 0.1 กก.', bal(g)['สาหร่าย (ดิบ)'], 0.1);
eq('วุ้นเส้นเกาหลี 0.5 กก.', bal(g)['วุ้นเส้นเกาหลี (ดิบ)'], 0.5);

section('สะกด "แพ้ค" กับของดิบที่ซื้อยกแพ็ค');
g = fresh();
out = send(g, ['ฟองเต้าหู้ 22 แพ้ค 471.68 บาท', 'ช้อน 5 แพ้ค 57.7บาท',
               'มาม่า 2 แพ้ค 218 บาท'].join('\n'), 'r2');
eq('ฟองเต้าหู้ 22 แพ็ค = 264 อัน', bal(g)['ฟองเต้าหู้ม้วน (ดิบ)'], 264);
eq('ช้อน 5 แพ็ค = 500 อัน', bal(g)['ช้อน'], 500);
eq('มาม่า 2 แพ็ค เข้ามาม่าเปล่า', bal(g)['มาม่าเปล่า (ดิบ)'], 2);
eq('ไม่หยิบเลข 35 จากชื่อ', /35 หน่วย/.test(out), false);

section('ของที่ต้องทำเอง ไม่เข้าครัวกลาง');
g = fresh();
out = send(g, 'พันเห็ดเข็ม 8 ไม้', 'r3');
eq('ไม่ลงสต็อก', bal(g)['หมูพันเห็ดเข็มทอง'] || 0, 0);
eq('บอกให้ไปแท็บแพ็คของ', /แพ็คของ/.test(out), true);

section('ค่าใช้จ่ายของสาขา พิมพ์ในกลุ่มครัวกลาง');
g = fresh();
out = send(g, ['ค่าแก๊ส 450 ทรัพย์พัฒนา', 'ค่าน้ำแข็ง 40 บัตร ตลาดทรัพย์พัฒนา', 'ค่าถุง 9',
               'น้ำดำ 2 ถุง 150 ทรัพย์พัฒนา'].join('\n'), 'br1');
const ex = g.__env.SHEETS[g.INTAKE_EXPENSE_SHEET];
const exCol = h => ex.headers.indexOf(h);
const exRows = ex.rows.map(r => [r[exCol('ประเภท')], r[exCol('สาขา')], r[exCol('จำนวนเงิน')], r[exCol('วิธีจ่าย')]]);
eq('ค่าแก๊สลงสาขา', exRows[0], ['ค่าแก๊ส', 'ตลาดทรัพย์พัฒนา', 450, 'โอน']);
eq('ชื่อเต็ม + บัตร ก็ได้', exRows[1], ['ค่าน้ำแข็ง', 'ตลาดทรัพย์พัฒนา', 40, 'บัตรเครดิต']);
eq('ไม่บอกสาขา = ครัวกลาง', exRows[2][1], 'ครัวกลาง');
eq('ไม่มีชื่อสาขาติดในรายละเอียด', ex.rows.some(r => /ทรัพย์/.test(String(r[exCol('รายละเอียด')]))), false);
eq('ตอบกลับบอกว่าลงสาขา', /ค่าแก๊ส — 450 บาท.*→ ตลาดทรัพย์พัฒนา/.test(out), true);
eq('ของที่ซื้อเข้าสต็อกยังเข้าครัวกลาง', bal(g)['น้ำดำ'], 2);
eq('ไม่ใช่ค่าใช้จ่ายของสาขา', g.stockBalances_()['ตลาดทรัพย์พัฒนา'] && g.stockBalances_()['ตลาดทรัพย์พัฒนา']['น้ำดำ'] || 0, 0);

section('ชื่อใหม่ของหมู/ไก่ พิมพ์เข้าไลน์ได้ทั้งชื่อใหม่และชื่อเก่า');
g = fresh();
out = send(g, ['ไส้กรอกแดง 1 แพ็ค 60 บาท', 'หมูไม่ติดมัน 1 โล 140', 'สะโพกหมู 1 โล 140',
               'หมูติดมัน 2 โล 260', 'หัวไหล่หมูหั่นชิ้น 1 โล 128', 'ไก่ 1 โล 84',
               'อกไก่ 0.5 โล 42'].join('\n'), 'r4');
eq('ไส้กรอกแดง 1 แพ็ค', bal(g)['ไส้กรอกแดง (ดิบ)'], 1);
eq('หมูไม่ติดมัน + สะโพกหมู (ชื่อเก่า) = 2 โล', bal(g)['หมูไม่ติดมัน (ดิบ)'], 2);
eq('หมูติดมันสไลซ์ 2 โล', bal(g)['หมูติดมันสไลซ์ (ดิบ)'], 2);
eq('หั่นชิ้นเข้าตัวหั่นชิ้น', bal(g)['หมูติดมันหั่นชิ้น (ดิบ)'], 1);
eq('ไก่ + อกไก่ (ชื่อเก่า) = 1.5 โล', bal(g)['ไก่ (ดิบ)'], 1.5);
eq('ไม่มีคำเตือน', /ยังไม่ได้ลงสต็อก/.test(out), false);

module.exports = { send, bal, ctx };
if (require.main === module) process.exit(done().fail ? 1 : 0);
