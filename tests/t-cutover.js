process.env.TZ = 'Asia/Bangkok';
const { makeCheck } = require('./harness');
const { fresh, push, D, SHOP } = require('./fixture');
const { buy, pack, ship, count, val } = require('./t-cost');
const { eq, section, done } = makeCheck('เริ่มนับใหม่ 1/10 เฉพาะสาขา');

const OCT = 9;   // เดือนใน Date() นับจาก 0
function sale(g, ymd, net) { push(g, g.SHEET_ORDERS, { 'วันที่': ymd, 'สาขา': SHOP, 'ยอดสุทธิ': net }); }

const g = fresh();
// ── กันยายน: ของเก่าที่ต้องไม่ถูกนำมาคิดที่สาขา ──
buy(g, 1, 'ดอลลี่ (ดิบ)', 20, 1520, 's1');           // 76 บาท/กก.
pack(g, 2, 'ดอลลี่', 400, [['ดอลลี่ (ดิบ)', 20]]);    // 3.8 บาท/ไม้
ship(g, 3, 'ดอลลี่', 100);                           // ก.ย. ส่งไป 380
sale(g, '2026-09-20', 9999);                          // ยอดขาย ก.ย.
count(g, 25, SHOP, 'ดอลลี่', 12);                      // นับ ก.ย.

section('ก่อนตั้ง — เห็นของเดือนกันยาปนอยู่');
let s = g.costSummary_();
eq('รายได้สาขามีของ ก.ย.', s.pl[SHOP]['รายได้'], 9999);
eq('ค้างชำระมีของ ก.ย.', s.owed[SHOP]['ค้างชำระ'], 380);

g.setLocationStart(SHOP, '2026-10-01');
g.cacheClear_();

section('หลังตั้ง 1/10 — สาขาเริ่มใหม่ ครัวกลางเดินต่อ');
s = g.costSummary_();
eq('รายได้ ก.ย. ไม่ถูกนำมาคิด', (s.pl[SHOP] || { รายได้: 0 })['รายได้'], 0);
eq('หนี้ ก.ย. ไม่ถูกนำมาคิด', (s.owed[SHOP] || { ค้างชำระ: 0 })['ค้างชำระ'], 0);
eq('ครัวกลางยังโดนตัดของที่ส่งไปใน ก.ย.', val(g, g.CENTRAL, 'ดอลลี่'), 1140);
eq('ของดิบครัวกลางไม่หาย (แพ็คไปหมดแล้ว)', val(g, g.CENTRAL, 'ดอลลี่ (ดิบ)'), 0);
eq('สาขายังไม่มีของ รอนับวันแรก', val(g, SHOP, 'ดอลลี่'), 0);
eq('การนับ ก.ย. ไม่โชว์เป็นนับล่าสุด', g.lastCountInfo_()[SHOP], undefined);

section('1/10 เช้า — นับยอดตั้งต้น');
count(g, 1, SHOP, 'ดอลลี่', 30, OCT, 8);
s = g.costSummary_();
// ยอดตั้งต้นสาขา = ของที่ครัวกลางส่งไปก่อนเริ่มนับ สาขาไม่ได้จ่ายคืน → ไม่ใช่ต้นทุนของสาขา
eq('ยอดตั้งต้นสาขามูลค่า 0 (ไม่ได้จ่ายคืนครัวกลาง)', val(g, SHOP, 'ดอลลี่'), 0);
eq('ยอดตั้งต้นไม่ใช่ค่าใช้จ่ายวัตถุดิบ', s.pl[SHOP]['ค่าใช้จ่ายวัตถุดิบ'], 0);
eq('ยอดตั้งต้นไม่ใช่หนี้', (s.owed[SHOP] || { ค้างชำระ: 0 })['ค้างชำระ'], 0);
eq('ไม่มีคำเตือนเรื่องราคา 0', s.warn.filter(w => /ราคาทุน/.test(w.msg)).length, 0);

section('1/10 ระหว่างวัน — ส่งเพิ่ม 20 ไม้ ขายได้ 500');
ship(g, 1, 'ดอลลี่', 20, OCT, 11);
sale(g, '2026-10-01', 500);
s = g.costSummary_();
eq('หนี้เฉพาะของที่ส่งวันนี้ 76', s.owed[SHOP]['ค้างชำระ'], 76);
eq('รายได้เฉพาะวันนี้ 500', s.pl[SHOP]['รายได้'], 500);

section('1/10 ปิดร้าน — นับรอบสอง เหลือ 35');
count(g, 1, SHOP, 'ดอลลี่', 35, OCT, 21);
s = g.costSummary_();
// 30 + 20 − 35 = ใช้ไป 15 ไม้ — เข้าก่อนออกก่อน หยิบจากยอดตั้งต้น (ทุน 0) ก่อน
eq('ใช้ไป 15 ไม้จากยอดตั้งต้น = 0 บาท', s.pl[SHOP]['ค่าใช้จ่ายวัตถุดิบ'], 0);
eq('กำไรขั้นต้น 500', s.pl[SHOP]['กำไรขั้นต้น'], 500);
eq('เหลือ 35 ไม้ = ตั้งต้น 15 (0) + ที่ส่ง 20 (76)', val(g, SHOP, 'ดอลลี่'), 76);
eq('นับล่าสุดคือรอบปิดร้าน', g.lastCountInfo_()[SHOP].n, 1);

section('รายงานเดือนตุลา');
const rp = g.monthlyReport('2026-10', SHOP);
eq('ยอดขายตุลา 500', rp.sales, 500);

section('ครัวกลางไม่โดนเส้นของสาขา');
g.clearLocationStart(SHOP); g.cacheClear_();
eq('ยกเลิกเส้นแล้วรายได้ ก.ย. กลับมา', g.costSummary_().pl[SHOP]['รายได้'], 10499);

section('มีเส้นทั้งระบบเก่าค้างอยู่ ยอดตั้งต้นสาขาก็ยังเป็น 0 ไม่เตือน');
const g2 = fresh();
buy(g2, 1, 'ดอลลี่ (ดิบ)', 20, 1520, 'x1');
pack(g2, 2, 'ดอลลี่', 400, [['ดอลลี่ (ดิบ)', 20]]);
g2.setStartDate('2026-09-26');                 // เส้นเก่าจากตอนล้างระบบ
g2.setLocationStart(SHOP, '2026-10-01');
count(g2, 1, SHOP, 'ดอลลี่', 30, OCT, 8);
eq('ยอดตั้งต้นสาขา 0', val(g2, SHOP, 'ดอลลี่'), 0);
eq('ไม่มีคำเตือนราคา 0', g2.costSummary_().warn.filter(w => /ราคาทุน/.test(w.msg)).length, 0);

section('ยอดตั้งต้นสาขาที่ไม่มีราคา ไม่ต้องเตือน (ตั้งใจให้เป็น 0)');
const g3 = fresh();
g3.setLocationStart(SHOP, '2026-10-01');
count(g3, 1, SHOP, 'ไส้กรอกอันเล็ก', 20, OCT, 8);
eq('ไม่เตือน', g3.costSummary_().warn.some(w => w.item === 'ไส้กรอกอันเล็ก'), false);
// แต่ของที่นับเกินหลังรอบตั้งต้นแล้วไม่รู้ราคา ยังต้องเตือน
count(g3, 2, SHOP, 'ไส้กรอกอันเล็ก', 30, OCT, 21);
eq('นับเกินหลังฐานยังเตือน', g3.costSummary_().warn.some(w => w.item === 'ไส้กรอกอันเล็ก'), true);

section('ครัวกลางกับสาขาเริ่มใหม่พร้อมกัน 1/10');
const g4 = fresh();
buy(g4, 1, 'ดอลลี่ (ดิบ)', 20, 1520, 'y1');            // 76 บาท/กก.
pack(g4, 2, 'ดอลลี่', 400, [['ดอลลี่ (ดิบ)', 20]]);     // 3.8 บาท/ไม้
ship(g4, 3, 'ดอลลี่', 100);
sale(g4, '2026-09-20', 9999);
g4.setStartDate('2026-10-01');
let s4 = g4.costSummary_();
eq('ครัวกลางยังไม่มีของ รอนับวันแรก', val(g4, g4.CENTRAL, 'ดอลลี่'), 0);
eq('รายได้ ก.ย. ไม่นับ', (s4.pl[SHOP] || { รายได้: 0 })['รายได้'], 0);
count(g4, 1, g4.CENTRAL, 'ดอลลี่', 200, OCT, 7);           // ฐานครัวกลาง
count(g4, 1, g4.CENTRAL, 'ดอลลี่ (ดิบ)', 5, OCT, 7);
count(g4, 1, SHOP, 'ดอลลี่', 30, OCT, 8);                   // ฐานสาขา
s4 = g4.costSummary_();
eq('ฐานครัวกลางมีมูลค่า 200 × 3.8', val(g4, g4.CENTRAL, 'ดอลลี่'), 760);
eq('ของดิบครัวกลางมีมูลค่า 5 × 76', val(g4, g4.CENTRAL, 'ดอลลี่ (ดิบ)'), 380);
eq('ฐานสาขามูลค่า 0', val(g4, SHOP, 'ดอลลี่'), 0);
eq('ฐานไม่ใช่ค่าใช้จ่ายของใคร', [s4.pl[g4.CENTRAL]['ค่าใช้จ่ายวัตถุดิบ'], s4.pl[SHOP]['ค่าใช้จ่ายวัตถุดิบ']], [0, 0]);
ship(g4, 1, 'ดอลลี่', 20, OCT, 11);
count(g4, 1, SHOP, 'ดอลลี่', 35, OCT, 21);
s4 = g4.costSummary_();
eq('ครัวกลางลดลง 20 ไม้', val(g4, g4.CENTRAL, 'ดอลลี่'), 684);
eq('หนี้สาขาเฉพาะของที่ส่ง 1/10', s4.owed[SHOP]['ค้างชำระ'], 76);
eq('สาขาใช้ไป 15 ไม้จากฐาน = 0', s4.pl[SHOP]['ค่าใช้จ่ายวัตถุดิบ'], 0);

section('เลื่อนฐานสาขาไป 5/10 ก่อนขาย (ครัวกลางยังเริ่ม 1/10)');
const g5 = fresh();
buy(g5, 25, 'ดอลลี่ (ดิบ)', 20, 1520, 'z1');
pack(g5, 26, 'ดอลลี่', 400, [['ดอลลี่ (ดิบ)', 20]]);
g5.setStartDate('2026-10-01');
count(g5, 1, g5.CENTRAL, 'ดอลลี่', 400, OCT, 7);       // ฐานครัวกลาง 1/10
count(g5, 1, SHOP, 'ดอลลี่', 30, OCT, 10);             // ฐานเดิมของสาขา 1/10
ship(g5, 3, 'ดอลลี่', 50, OCT, 11);                    // ส่งช่วงที่ข้อมูลไม่ครบ
sale(g5, '2026-10-02', 800);
count(g5, 5, SHOP, 'ดอลลี่', 40, OCT, 9);              // ฐานใหม่ 5/10 ก่อนขาย
ship(g5, 5, 'ดอลลี่', 20, OCT, 11);
sale(g5, '2026-10-05', 500);
count(g5, 5, SHOP, 'ดอลลี่', 45, OCT, 21);             // เย็น 5/10
sale(g5, '2026-10-06', 300);
count(g5, 6, SHOP, 'ดอลลี่', 30, OCT, 21);             // เย็น 6/10
g5.setLocationStart(SHOP, '2026-10-05');
const s5 = g5.costSummary_();
eq('รายได้นับตั้งแต่ 5/10', s5.pl[SHOP]['รายได้'], 800);
eq('หนี้เฉพาะของที่ส่ง 5/10 (20 ไม้)', s5.owed[SHOP]['ค้างชำระ'], 76);
// 40 + 20 − 45 = 15 · 45 − 30 = 15 → ใช้ไป 30 ไม้ หยิบจากฐาน 40 ไม้ (ทุน 0) ก่อน
eq('ใช้ไป 30 ไม้จากฐาน = 0', s5.pl[SHOP]['ค่าใช้จ่ายวัตถุดิบ'], 0);
eq('เหลือ 30 ไม้ = ฐาน 10 (0) + ที่ส่ง 20 (76)', val(g5, SHOP, 'ดอลลี่'), 76);
eq('ครัวกลางยังตัดของที่ส่ง 3/10', val(g5, g5.CENTRAL, 'ดอลลี่'), (400 - 50 - 20) * 3.8);
eq('ครัวกลางไม่โดนเลื่อน รายจ่าย/ฐานเดิมยังอยู่', g5.costStartDate_(g5.CENTRAL) < g5.costStartDate_(SHOP), true);

section('เริ่มใหม่ทุกที่จากหน้า Apps Script (ไม่มีกล่องถาม) = วันนี้');
{
  const g6 = fresh();
  g6.promptStartDate();
  const today = g6.Utilities.formatDate(new Date(), 'Asia/Bangkok', 'yyyy-MM-dd');
  eq('ตั้ง ACC_START_DATE เป็นวันนี้', g6.__env.PROPS.ACC_START_DATE, today);
  // เส้นเฉพาะสาขาที่เก่ากว่า ไม่บังเส้นใหม่
  g6.__env.PROPS.ACC_START_BY_LOC = JSON.stringify({ [SHOP]: '2026-10-05 22:38' });
  g6.cacheClear_();
  eq('สาขาใช้เส้นใหม่ (ใหม่กว่า)', g6.costStartDate_(SHOP), g6.costYmdTime_(today));
}

process.exit(done().fail ? 1 : 0);
