process.env.TZ = 'Asia/Bangkok';
const { makeCheck } = require('./harness');
const { fresh, push, SHOP } = require('./fixture');
const { eq, section, done } = makeCheck('ของที่ต้องทิ้ง — แจ้งหลังเช็คสต็อกสาขา');

const T = s => new Date(s + '+07:00');
const P = 'หมูพันเห็ดเข็มทอง';
function setup() {
  const g = fresh();
  g.__env.PROPS.LINE_CHANNEL_ACCESS_TOKEN = 'tok';
  return g;
}
const cnt = (g, when, item, qty) => push(g, g.SHEET_COUNT, { 'วันที่เวลา': T(when), 'สาขา': SHOP,
  'รายการ': item, 'จำนวน': qty, 'ประเภท': 'เช็คสต็อก' });
const inn = (g, when, item, qty) => push(g, g.SHEET_INCOMING, { 'วันที่เวลา': T(when), 'สาขา': SHOP,
  'รายการ': item, 'จำนวน': qty, 'ประเภท': 'ของเข้าร้าน' });
const check = (g, when, item, qty) => g.expiryAfterCount_(SHOP, [{ item: g.findStockItem_(item), counted: qty }], T(when));

section('อายุของแต่ละแบบ');
let g = setup();
const d = n => g.branchShelfDays_(g.findStockItem_(n));
eq('ของพัน 3 วัน', [d('หมูพันเห็ดเข็มทอง'), d('หมูพันสาหร่าย'), d('หมูพันเห็ดชิเมจิ')], [3, 3, 3]);
eq('หมู 5 วัน', [d('หมูไม่ติดมัน'), d('หมูติดมันสไลซ์'), d('หมูติดมันหั่นชิ้น')], [5, 5, 5]);
eq('ดอลลี่ 5 วัน', d('ดอลลี่'), 5);
eq('หมึกกรอบ แมงกะพรุน 7 วัน', [d('ปลาหมึกกรอบ'), d('แมงกะพรุน')], [7, 7]);
eq('ลูกชิ้น/ที่เหลือ 7 วัน', [d('เต้าชีส'), d('เต้าหู้หมู'), d('ผักกาดขาว')], [7, 7, 7]);
eq('ของไม่ได้ขาย ไม่นับ', [d('หม่าล่า(ผสมแล้ว)'), d('นมข้นจืด'), d('น้ำจิ้มงา (กระปุก)'), d('กะหล่ำ')], [0, 0, 0, 0]);
eq('ของดิบ/ของใช้ ไม่นับ', [d('ดอลลี่ (ดิบ)'), d('ช้อน')], [0, 0]);

section('ตัวอย่างจริง: หมูพันเห็ดเข็มทองเข้า 10/10 เช้า');
cnt(g, '2026-10-09T21:00:00', P, 0);
inn(g, '2026-10-10T09:00:00', P, 20);
cnt(g, '2026-10-12T21:00:00', P, 6);
eq('12/10 เหลือ 6 — ยังขายได้ ไม่แจ้ง', check(g, '2026-10-12T21:00:00', P, 6).length, 0);
cnt(g, '2026-10-13T21:00:00', P, 1);
let r = check(g, '2026-10-13T21:00:00', P, 1);
eq('13/10 เหลือ 1 ไม้ → แจ้ง', r.length, 1);
eq('ทิ้ง 1 ไม้', r[0].qty, 1);
eq('ทิ้งวันที่ 14/10', r[0].toss, '2026-10-14');
let txt = g.expiryText_(SHOP, r, T('2026-10-13T21:00:00'));
eq('ข้อความ', /• หมูพันเห็ดเข็มทอง 1 ไม้ — ทิ้งวันที่ 14\/10\/2026 ก่อนขาย \(เข้า 10\/10\/2026 อยู่ได้ 3 วัน\)/.test(txt), true);

section('13/10 ขายหมด — ไม่แจ้ง');
g = setup();
cnt(g, '2026-10-09T21:00:00', P, 0);
inn(g, '2026-10-10T09:00:00', P, 20);
cnt(g, '2026-10-13T21:00:00', P, 0);
eq('ไม่เหลือ ไม่แจ้ง', check(g, '2026-10-13T21:00:00', P, 0).length, 0);

section('ของเข้าใหม่อีกรอบ — ขายของเก่าไปก่อน ที่เหลือเป็นของใหม่');
g = setup();
cnt(g, '2026-10-09T21:00:00', P, 0);
inn(g, '2026-10-10T09:00:00', P, 20);
inn(g, '2026-10-12T09:00:00', P, 10);
cnt(g, '2026-10-13T21:00:00', P, 8);
eq('เหลือ 8 ≤ ของใหม่ 10 → ไม่แจ้ง', check(g, '2026-10-13T21:00:00', P, 8).length, 0);
g = setup();
cnt(g, '2026-10-09T21:00:00', P, 0);
inn(g, '2026-10-10T09:00:00', P, 20);
inn(g, '2026-10-12T09:00:00', P, 10);
cnt(g, '2026-10-13T21:00:00', P, 12);
r = check(g, '2026-10-13T21:00:00', P, 12);
eq('เหลือ 12 → ของเก่า 2 ไม้ต้องทิ้ง', r.length && r[0].qty, 2);

section('นับเช้าวันที่ 14/10 (ลืมนับเย็น) — ทิ้งเลยก่อนขาย');
g = setup();
cnt(g, '2026-10-09T21:00:00', P, 0);
inn(g, '2026-10-10T09:00:00', P, 20);
cnt(g, '2026-10-14T09:00:00', P, 3);
r = check(g, '2026-10-14T09:00:00', P, 3);
eq('3 ไม้', r.length && r[0].qty, 3);
eq('ทิ้งเลย', /ทิ้งเลยก่อนขาย \(ครบกำหนดทิ้ง 14\/10\/2026\)/.test(g.expiryText_(SHOP, r, T('2026-10-14T09:00:00'))), true);

section('หมู 5 วัน · ของเข้าไม่ได้ลง (นับเจอเพิ่ม) ไม่โดนสั่งทิ้ง');
g = setup();
cnt(g, '2026-10-09T21:00:00', 'หมูไม่ติดมัน', 0);
inn(g, '2026-10-10T09:00:00', 'หมูไม่ติดมัน', 10);
eq('14/10 ยังไม่แจ้ง', check(g, '2026-10-14T21:00:00', 'หมูไม่ติดมัน', 4).length, 0);
cnt(g, '2026-10-15T21:00:00', 'หมูไม่ติดมัน', 4);
eq('15/10 เหลือ 4 → ทิ้ง 16/10', check(g, '2026-10-15T21:00:00', 'หมูไม่ติดมัน', 4)[0].toss, '2026-10-16');
g = setup();
cnt(g, '2026-10-09T21:00:00', P, 0);
cnt(g, '2026-10-12T21:00:00', P, 15);            // ของมาส่ง 12/10 แต่ไม่ได้ลงของเข้าร้าน
cnt(g, '2026-10-13T21:00:00', P, 5);
eq('ถือว่าเข้า 12/10 → 13/10 ยังไม่ต้องทิ้ง', check(g, '2026-10-13T21:00:00', P, 5).length, 0);

section('ของเสียที่ลงแล้ว ตัดของเก่าก่อน');
g = setup();
cnt(g, '2026-10-09T21:00:00', P, 0);
inn(g, '2026-10-10T09:00:00', P, 20);
inn(g, '2026-10-12T09:00:00', P, 10);
push(g, g.SHEET_WASTE, { 'วันที่เวลา': T('2026-10-13T20:00:00'), 'สาขา': SHOP, 'รายการ': P, 'จำนวน': 2 });
cnt(g, '2026-10-13T21:00:00', P, 10);
eq('ทิ้งของเก่าไปแล้ว เหลือของใหม่ 10 → ไม่แจ้ง', check(g, '2026-10-13T21:00:00', P, 10).length, 0);

section('นับจริงผ่านหน้าเว็บ → แจ้งกลุ่มไลน์สาขา + ส่งข้อความกลับให้หน้าเว็บ');
{
  const g2 = setup();
  const now = Date.now(), ago = h => new Date(now - h * 3600000);
  push(g2, g2.SHEET_COUNT, { 'วันที่เวลา': ago(24 * 5), 'สาขา': SHOP, 'รายการ': P, 'จำนวน': 0, 'ประเภท': 'เช็คสต็อก' });
  push(g2, g2.SHEET_INCOMING, { 'วันที่เวลา': ago(24 * 4.5), 'สาขา': SHOP, 'รายการ': P, 'จำนวน': 20, 'ประเภท': 'ของเข้าร้าน' });
  const want = g2.SCOPE_SHOP;
  const rows = g2.getStockItems_().filter(i => !i.scope || i.scope === want).map(i => i.level
    ? { item: i.name, level: 'มาก ไม่ต้องเติม' }
    : { item: i.name, packs: '', rem: i.name === P ? 1 : 0, pieces: '' });
  const res = g2.handleStockCount_({ token: 't', location: SHOP, rows });
  eq('บันทึกได้', res.success, true);
  eq('บอกหน้าเว็บว่ามีของต้องทิ้ง', res.toss, 1);
  eq('ข้อความให้พนักงาน', /🗑️ ของที่ต้องทิ้งก่อนขาย[\s\S]*หมูพันเห็ดเข็มทอง 1 ไม้/.test(res.tossText), true);
  const sent = g2.__env.SENT.filter(x => x.to === 'Cshop').map(x => x.messages.map(m => m.text).join('\n')).join('\n');
  eq('ส่งกลุ่มไลน์สาขา', /🗑️ ของที่ต้องทิ้งก่อนขาย/.test(sent), true);
}

done();
