process.env.TZ = 'Asia/Bangkok';
const { makeCheck } = require('./harness');
const { fresh, itemRow, itemNames } = require('./fixture');
const { eq, section, done } = makeCheck('รายการสินค้า');

const g = fresh();
const names = itemNames(g);
const has = n => names.indexOf(n) !== -1;
const u = (n, k) => { const r = itemRow(g, n); return r ? r[k] : undefined; };
const unit3 = n => [u(n, 'หน่วยย่อย'), u(n, 'หน่วยแพ็ค'), u(n, 'หน่วยย่อยต่อแพ็ค')];

section('เอาออก 5 รายการ (หมูพันเห็ดชิเมจิกลับมาแล้ว 7/10)');
['สันคอสไลซ์', 'ผักบุ้ง', 'สันนอกสไลซ์', 'หมูพันผักกาดขาว', 'ถ้วย 750'].forEach(n => {
  eq('ไม่มี "' + n + '"', has(n), false);
  eq('ไม่มี "' + n + ' (ดิบ)"', has(n + ' (ดิบ)'), false);
});

section('เปลี่ยนชื่อ ทั้งของแพ็คและของดิบ');
// ของแพ็ค (สาขา) ใช้ชื่อที่ขาย · ของดิบ (ครัวกลาง) ใช้ชื่อชิ้นส่วนที่ซื้อ
[['หมูไม่ติดมัน', 'สะโพกหมูสไลซ์'], ['หมูติดมันสไลซ์', 'หัวไหล่หมูติดหนังสไลซ์'],
 ['หมูติดมันหั่นชิ้น', 'หัวไหล่หมูติดหนังหั่นชิ้น']
].forEach(([packed, raw]) => {
  eq(packed + ' มี (สาขา)', has(packed), true);
  eq(raw + ' (ดิบ) มี (ครัวกลาง)', has(raw + ' (ดิบ)'), true);
  eq(packed + ' (ดิบ) ไม่มีแล้ว', has(packed + ' (ดิบ)'), false);
  eq(raw + ' ไม่มีเป็นของแพ็ค', has(raw), false);
  eq('แพ็ค ' + packed + ' ตัดจาก ' + raw + ' (ดิบ)', g.findStockItem_(packed).raws, [raw + ' (ดิบ)']);
  eq('ชื่อแพ็คเก่าแมปมาชื่อที่ขาย', g.ITEM_RENAME[raw], packed);
  eq('ของดิบชื่อเดิมแมปไปชื่อชิ้นส่วน', g.ITEM_RENAME[packed + ' (ดิบ)'], raw + ' (ดิบ)');
});
eq('ไก่ มี', has('ไก่'), true);
eq('ไก่ (ดิบ) มี', has('ไก่ (ดิบ)'), true);
eq('อกไก่เนื้อล้วนติดหนัง ไม่เหลือ', has('อกไก่เนื้อล้วนติดหนัง'), false);
eq('หมูไม่ติดมันนับเป็นไม้', u('หมูไม่ติดมัน', 'หน่วยย่อย'), 'ไม้');
eq('ไก่แพ็คละ 10 ไม้ (8/10 ทุกอย่างแพ็คละ 10)', u('ไก่', 'หน่วยย่อยต่อแพ็ค'), 10);
eq('ไก่ (ดิบ) ชั่งเป็นโล', u('ไก่ (ดิบ)', 'หน่วยย่อย'), 'กก.');
eq('หมูที่เลือกพันได้ เหลือ 3 อย่าง', g.rawGroupOf_('@เนื้อหมู'),
   ['หัวไหล่หมูติดหนังสไลซ์ (ดิบ)', 'สะโพกหมูสไลซ์ (ดิบ)']);
eq('ไม่มีหมูสามชั้นสไลซ์', [has('หมูสามชั้นสไลซ์'), has('หมูสามชั้นสไลซ์ (ดิบ)')], [false, false]);
eq('ของพัน 3 ตัว', names.filter(n => /^หมูพัน/.test(n)).sort(),
   ['หมูพันสาหร่าย', 'หมูพันเห็ดชิเมจิ', 'หมูพันเห็ดเข็มทอง'].sort());
eq('หมูพันเห็ดชิเมจิ ใช้หมูที่เลือก + เห็ดชิเมจิ (ดิบ)', g.findStockItem_('หมูพันเห็ดชิเมจิ').raws, ['@เนื้อหมู', 'เห็ดชิเมจิ (ดิบ)']);
eq('เห็ดชิเมจิ (ดิบ) ชั่งเป็นโล', u('เห็ดชิเมจิ (ดิบ)', 'หน่วยย่อย'), 'กก.');
eq('ไม่มีไม้เห็ดชิเมจิเปล่า', has('เห็ดชิเมจิ'), false);

section('หน่วย');
eq('หม่าล่าผสม นับเป็นถุงล้วน', unit3('หม่าล่า(ผสมแล้ว)'), ['ถุง', 'แพ็ค', 1]);
eq('ถุงละ 400 กรัม ผสม 2:1:1', g.findStockItem_('หม่าล่า(ผสมแล้ว)').autoRaws,
   { 'เบสหม่าล่า': 200, 'ผงหม่าล่า': 100, 'พริกป่น': 100 });
eq('นมผง (ถุง) นับเป็นถุงล้วน', unit3('นมผง (ถุง)'), ['ถุง', 'แพ็ค', 1]);
eq('ถุงละนมผง 200 กรัม', g.findStockItem_('นมผง (ถุง)').autoRaws, { 'นมผง': 200 });
eq('ไม่มีนมข้นจืดแล้ว', g.findStockItem_('นมข้นจืด'), null);
eq('ถุงหูหิ้ว นับเป็นแพ็คอย่างเดียว', unit3('ถุงหูหิ้ว'), ['แพ็ค', 'แพ็ค', 1]);
eq('ถุงร้อนใหญ่ นับเป็นแพ็คอย่างเดียว', unit3('ถุงร้อนใหญ่'), ['แพ็ค', 'แพ็ค', 1]);
eq('ถุงร้อนเล็กไม่ได้แตะ', unit3('ถุงร้อนเล็ก'), ['ใบ', 'แพ็ค', 100]);
eq('กะหล่ำที่สาขาเป็นโล', unit3('กะหล่ำ'), ['กก.', 'แพ็ค', 1]);
eq('ต็อกเป็นถุง', u('ต็อกแท่งเล็ก', 'หน่วยย่อย'), 'ถุง');
eq('ชีสเป็นถุง', u('ชีส', 'หน่วยย่อย'), 'ถุง');

section('ไส้กรอกแดงเลิกขาย (8/10)');
eq('ไม่มีในรายการแล้ว', g.findStockItem_('ไส้กรอกแดง'), null);
eq('ของดิบก็ไม่มี', g.findStockItem_('ไส้กรอกแดง (ดิบ)'), null);


section('8/10 — ของส่งสาขาแพ็คละ 10 หมด ยกเว้นฟองเต้าหู้ม้วนกล่องละ 12');
{
  const g10 = fresh();
  eq('ไก่ 10', g10.findStockItem_('ไก่').perPack, 10);
  eq('มาม่าเปล่า 10 (แพ็ค)', [g10.findStockItem_('มาม่าเปล่า').perPack, g10.findStockItem_('มาม่าเปล่า').packUnit], [10, 'แพ็ค']);
  eq('น้ำจิ้มงา (กระปุก) 10', g10.findStockItem_('น้ำจิ้มงา (กระปุก)').perPack, 10);
  eq('น้ำจิ้มสุกี้ (กระปุก) 10', g10.findStockItem_('น้ำจิ้มสุกี้ (กระปุก)').perPack, 10);
  eq('ฟองเต้าหู้ม้วน กล่องละ 12', [g10.findStockItem_('ฟองเต้าหู้ม้วน').perPack, g10.findStockItem_('ฟองเต้าหู้ม้วน').packUnit], [12, 'กล่อง']);
  eq('ของดิบมาม่าเปล่ายังถุงละ 21', g10.findStockItem_('มาม่าเปล่า (ดิบ)').perPack, 21);
  // ชีตเดิมที่ยังเป็น 20 / 50 — fixItemList แก้ให้
  const S0 = g10.__env.SHEETS[g10.SHEET_ITEMS], pp = S0.headers.indexOf('หน่วยย่อยต่อแพ็ค');
  S0.rows.find(r => r[0] === 'ไก่')[pp] = 20;
  S0.rows.find(r => r[0] === 'น้ำจิ้มงา (กระปุก)')[pp] = 50;
  g10.cacheClear_(); g10.fixItemList(); g10.cacheClear_();
  eq('fixItemList แก้ไก่ในชีตเป็น 10', g10.findStockItem_('ไก่').perPack, 10);
  eq('fixItemList แก้น้ำจิ้มในชีตเป็น 10', g10.findStockItem_('น้ำจิ้มงา (กระปุก)').perPack, 10);
}

process.exit(done().fail ? 1 : 0);
